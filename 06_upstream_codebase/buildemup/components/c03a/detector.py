def _detect_ec008(
    gap_analysis: DesignGapAnalysis, brief: Brief
) -> Optional[ExtremeCase]:
    """EC-008: BUDGET_CATASTROPHICALLY_LOW (BUDGET)

    Detection: cost_estimate.exact_value > budget × 1.5
    The 1.25× soft warn is C2's job (NOT detector's).

    Note: cost_estimate is a CostEstimate dataclass with field
    `exact_value` (not midpoint_inr). Read accordingly.
    """
    cost_estimate = gap_analysis.practical_report.cost_estimate
    if cost_estimate is None:
        return None

    estimate_inr = getattr(cost_estimate, "exact_value", None)
    if estimate_inr is None:
        return None

    budget_inr = brief.budget_range.max_rupees
    if budget_inr <= 0:
        return None

    if estimate_inr <= budget_inr * EC_008_HARD_RATIO:
        return None  # No EC-008 — 1.25× is C2's concern

    estimate_l = estimate_inr / 100_000
    budget_l = budget_inr / 100_000
    gap_l = estimate_l - budget_l
    gap_pct = (gap_l / budget_l) * 100

    user_facing_message = (
        f"Building this brief in {brief.plot.city.title()} costs about "
        f"₹{estimate_l:.0f} L. Your budget is ₹{budget_l:.0f} L. "
        f"The gap is ₹{gap_l:.0f} L (~{gap_pct:.0f}%). For context: "
        f"phased construction in India typically absorbs gaps up to "
        f"~30-40%; yours is beyond that."
    )

    framing_line = (
        "The gap between your budget and the cost of this brief is too "
        "large for normal solutions like phased construction or top-up "
        "loans. You'll need a fundamental decision."
    )

    related_check = _find_check_in_blocking(
        gap_analysis.practical_report, "budget_feasibility"
    )
    blocking_gap_ids = (("budget_feasibility",) if related_check else ())

    return ExtremeCase(
        case_id=ExtremeCaseId.EC_008_BUDGET_CATASTROPHICALLY_LOW,
        category=ExtremeCaseCategory.BUDGET,
        blocking_gap_ids=blocking_gap_ids,
        user_facing_message=user_facing_message,
        framing_line=framing_line,
        resolution_probability=ResolutionProbability.NOT_APPLICABLE,
        options=_make_placeholder_options(),
        detected_at_iteration=0,
    )


def _detect_ec009(
    gap_analysis: DesignGapAnalysis, brief: Brief
) -> Optional[ExtremeCase]:
    """EC-009: SOIL_REQUIRES_PILE_BUDGET_LOW (SITE+BUDGET intersect)

    Detection: soil.requires_pile == True AND
               (c7_estimate + pile_cost) > budget × 1.2

    Reads soil from C2's soil_type or soil_type_practical CheckResult
    (in either blocking_issues or soft_warnings).
    Reads pile cost from CheckResult.details if available.
    """
    # Look for soil indication in blocking_issues OR soft_warnings
    soil_check = None
    for cr in (gap_analysis.practical_report.blocking_issues
               + gap_analysis.practical_report.soft_warnings):
        if cr.check_id in ("soil_type", "soil_type_practical"):
            soil_check = cr
            break

    if soil_check is None:
        return None

    requires_pile = soil_check.details.get("requires_pile", False)
    if not requires_pile:
        return None

    cost_estimate = gap_analysis.practical_report.cost_estimate
    if cost_estimate is None:
        return None

    base_estimate_inr = getattr(cost_estimate, "exact_value", None)
    if base_estimate_inr is None:
        return None

    pile_cost_inr = soil_check.details.get("pile_cost_inr", 500_000)  # default ₹5L
    total_inr = base_estimate_inr + pile_cost_inr
    budget_inr = brief.budget_range.max_rupees

    if total_inr <= budget_inr * EC_009_BUDGET_BUFFER_RATIO:
        return None

    soil_class = soil_check.details.get("soil_class", "soft soil")
    base_l = base_estimate_inr / 100_000
    pile_l = pile_cost_inr / 100_000
    total_l = total_inr / 100_000
    budget_l = budget_inr / 100_000

    user_facing_message = (
        f"Your site has {soil_class} soil. That requires pile foundation "
        f"(about ₹{pile_l:.0f} L extra). Combined with your build "
        f"estimate of ₹{base_l:.0f} L, you'd need ₹{total_l:.0f} L. "
        f"Your budget is ₹{budget_l:.0f} L."
    )

    framing_line = (
        "Your soil needs a pile foundation, which adds significant cost. "
        "Combined with your build estimate, that exceeds your budget."
    )

    blocking_gap_ids = []
    if soil_check.severity == CheckSeverity.HARD_FAIL:
        blocking_gap_ids.append(soil_check.check_id)
    budget_check = _find_check_in_blocking(
        gap_analysis.practical_report, "budget_feasibility"
    )
    if budget_check:
        blocking_gap_ids.append("budget_feasibility")

    return ExtremeCase(
        case_id=ExtremeCaseId.EC_009_SOIL_REQUIRES_PILE_BUDGET_LOW,
        category=ExtremeCaseCategory.SITE,  # SITE+BUDGET intersect; SITE is primary
        blocking_gap_ids=tuple(blocking_gap_ids),
        user_facing_message=user_facing_message,
        framing_line=framing_line,
        resolution_probability=ResolutionProbability.NOT_APPLICABLE,
        options=_make_placeholder_options(),
        detected_at_iteration=0,
    )


def _detect_ec010(
    gap_analysis: DesignGapAnalysis, brief: Brief
) -> Optional[ExtremeCase]:
    """EC-010: APPROVAL_BLOCKER_UNREMEDIABLE (APPROVAL)

    Detection: any blocking CheckResult with check_id in EC_010_CHECK_IDS.
    Dedup: EC-004/005/007 cover their own check_ids; this only fires for
    fire/electric/watercourse blockers.

    Per-blocker resolution_probability:
      fire_tender_access → MEDIUM
      electric_line_clearance → MEDIUM (LT default) or LOW (HT)
      water_course_clearance → LOW
    """
    matching = [
        cr for cr in gap_analysis.practical_report.blocking_issues
        if cr.check_id in EC_010_CHECK_IDS
    ]
    if not matching:
        return None

    # If multiple, surface the highest-impact one (LOW resolution_probability first)
    def _probability_rank(cr: CheckResult) -> int:
        """Lower rank = higher severity for surfacing order."""
        if cr.check_id == "electric_line_clearance":
            prob = _classify_electric_line(cr)
        else:
            prob = EC_010_FIXED_PROBABILITY.get(
                cr.check_id, ResolutionProbability.MEDIUM
            )
        return {
            ResolutionProbability.LOW: 0,
            ResolutionProbability.MEDIUM: 1,
            ResolutionProbability.HIGH: 2,
        }.get(prob, 3)

    matching.sort(key=_probability_rank)
    primary = matching[0]

    # Determine resolution_probability for the primary check
    if primary.check_id == "electric_line_clearance":
        resolution_prob = _classify_electric_line(primary)
    else:
        resolution_prob = EC_010_FIXED_PROBABILITY.get(
            primary.check_id, ResolutionProbability.MEDIUM
        )

    # Build framing line per resolution_probability
    if resolution_prob == ResolutionProbability.LOW:
        framing_line = (
            "This kind of approval blocker is rarely resolvable on this "
            "plot. Most often, the realistic path is a different plot."
        )
        prob_explainer = "rarely resolvable through variance applications"
    else:  # MEDIUM (HIGH not used for these subtypes)
        framing_line = (
            "This kind of approval blocker often has a resolution path. "
            "Here's what we can try."
        )
        prob_explainer = (
            "often resolvable through minor design adjustments or "
            "local consultation"
        )

    blocker_description = primary.message[:200]  # truncate

    user_facing_message = (
        f"This site has an approval blocker: {blocker_description}. "
        f"This is {prob_explainer}. Without resolving this, the building "
        f"won't be approved."
    )

    return ExtremeCase(
        case_id=ExtremeCaseId.EC_010_APPROVAL_BLOCKER,
        category=ExtremeCaseCategory.APPROVAL,
        blocking_gap_ids=(primary.check_id,),
        user_facing_message=user_facing_message,
        framing_line=framing_line,
        resolution_probability=resolution_prob,
        options=_make_placeholder_options(),
        detected_at_iteration=0,
    )


