# Public API: ExtremeCaseDetector
# ──────────────────────────────────────────────────────────────────────

class ExtremeCaseDetector:
    """Detects all extreme cases in a DesignGapAnalysis.

    Public API:
        detect(gap_analysis, brief) -> tuple[ExtremeCase, ...]

    Returns ExtremeCase objects with placeholder options. S3
    (option_generator.py) replaces placeholders with real options.

    Order of returned cases: detection order (EC-001 through EC-010).
    Orchestrator (S6) handles priority sorting.
    """

    @staticmethod
    def detect(
        gap_analysis: DesignGapAnalysis,
        brief: Brief,
    ) -> tuple[ExtremeCase, ...]:
        """Detect all extreme cases in the gap analysis.

        Returns a tuple of ExtremeCase. Empty tuple if no blockers
        of EC-recognized type. Order is detection order, NOT priority
        order — orchestrator (S6) handles priority sorting.
        """
        detectors = [
            _detect_ec001, _detect_ec002, _detect_ec003,
            _detect_ec004, _detect_ec005, _detect_ec006,
            _detect_ec007, _detect_ec008, _detect_ec009,
            _detect_ec010,
        ]
        cases = [d(gap_analysis, brief) for d in detectors]
        return tuple(c for c in cases if c is not None)
