def _detect_ec006(
    gap_analysis: DesignGapAnalysis, brief: Brief
) -> Optional[ExtremeCase]:
    """EC-006: PRACTICAL_ENVELOPE_BELOW_BUILDABLE (LEGAL)

    Detection: practical envelope (user-stated setbacks) < min buildable.
    Dedup: only fires when user_stated_setbacks differ from
    nbc_compliant_setbacks (otherwise EC-001 covers the case).
    """
    user_setbacks = brief.user_stated_setbacks
    nbc_setbacks = brief.nbc_compliant_setbacks

    # Dedup check: if user setbacks == NBC setbacks, EC-001 covers it
    if (user_setbacks.front_m == nbc_setbacks.front_m and
        user_setbacks.rear_m == nbc_setbacks.rear_m and
        user_setbacks.side_left_m == nbc_setbacks.side_left_m and
        user_setbacks.side_right_m == nbc_setbacks.side_right_m):
        return None

    min_buildable_per_floor = _compute_min_buildable_per_floor_sqm(brief)
    practical_envelope_per_floor = _compute_envelope_area_sqm(
        brief, use_nbc_setbacks=False
    )

    if min_buildable_per_floor <= practical_envelope_per_floor:
        return None

    front_ft = user_setbacks.front_m * M_TO_FT
    rear_ft = user_setbacks.rear_m * M_TO_FT
    side_ft = (user_setbacks.side_left_m + user_setbacks.side_right_m) * M_TO_FT / 2
    envelope_sqft = practical_envelope_per_floor * SQM_TO_SQFT
    min_buildable_sqft = min_buildable_per_floor * SQM_TO_SQFT

    user_facing_message = (
        f"With your stated setbacks ({front_ft:.1f}/{rear_ft:.1f}/"
        f"{side_ft:.1f} ft), your buildable envelope shrinks to "
        f"{envelope_sqft:.0f} sqft. That's below the minimum needed for "
        f"any version of your brief ({min_buildable_sqft:.0f} sqft)."
    )

    framing_line = (
        "Even with the setbacks you specified, your plot doesn't have "
        "enough envelope for the smallest version of your brief."
    )

    related_check = _find_check_in_blocking(
        gap_analysis.practical_report, "envelope_sufficiency"
    )
    blocking_gap_ids = (("envelope_sufficiency",) if related_check else ())

    return ExtremeCase(
        case_id=ExtremeCaseId.EC_006_PRACTICAL_ENVELOPE_BELOW_BUILDABLE,
        category=ExtremeCaseCategory.LEGAL,
        blocking_gap_ids=blocking_gap_ids,
        user_facing_message=user_facing_message,
        framing_line=framing_line,
        resolution_probability=ResolutionProbability.NOT_APPLICABLE,
        options=_make_placeholder_options(),
        detected_at_iteration=0,
    )


