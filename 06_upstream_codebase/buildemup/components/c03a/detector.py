def _compute_min_buildable_per_floor_sqm(brief: Brief) -> float:
    """Sum of NBC-minimum room areas × circulation factor 1.35,
    divided across the floors the brief allocates.

    Used by EC-001 (against NBC envelope) and EC-006 (against
    user-stated envelope).
    """
    if not brief.floors:
        return 0.0

    total_room_area_sqm = 0.0
    for floor in brief.floors:
        for room_req in floor.rooms:
            nbc_min = NBC_MINIMUM_ROOM_SIZES_SQM[room_req.room_type]
            total_room_area_sqm += room_req.count * nbc_min

    total_with_circulation = total_room_area_sqm * CIRCULATION_FACTOR
    return total_with_circulation / len(brief.floors)


def _compute_envelope_area_sqm(brief: Brief, use_nbc_setbacks: bool) -> float:
    """Compute buildable envelope area for a brief.

    use_nbc_setbacks=True → use NBC-compliant setbacks (for EC-001)
    use_nbc_setbacks=False → use user-stated setbacks (for EC-006)
    """
    plot = brief.plot
    setbacks = (brief.nbc_compliant_setbacks
                if use_nbc_setbacks
                else brief.user_stated_setbacks)
    env_w = max(0.0, plot.width_m
                - setbacks.side_left_m - setbacks.side_right_m)
    env_d = max(0.0, plot.depth_m
                - setbacks.front_m - setbacks.rear_m)
    return env_w * env_d


def _find_check_in_blocking(
    report: FeasibilityReport, check_id: str
) -> Optional[CheckResult]:
    """Return the CheckResult with this check_id from blocking_issues,
    or None if not found.
    """
    for cr in report.blocking_issues:
        if cr.check_id == check_id:
            return cr
    return None


def _classify_electric_line(check_result: CheckResult) -> ResolutionProbability:
    """Determine HT vs LT from the check's details dict for EC-010.

    Default to MEDIUM if details don't specify line_type.
    Logged as v0.2-backlog item (add line_type field consistently).
    """
    line_type = str(check_result.details.get("line_type", "")).upper()
    if "HT" in line_type or "HIGH" in line_type:
        return ResolutionProbability.LOW
    return ResolutionProbability.MEDIUM


def _bhk_count(brief: Brief) -> int:
    """Count total bedrooms (master + regular) across all floors.
    Used by EC-002 to determine BHK-specific width tiers.
    """
    count = 0
    for floor in brief.floors:
        for room_req in floor.rooms:
            if room_req.room_type in (RoomType.BEDROOM_MASTER,
                                       RoomType.BEDROOM_REGULAR):
                count += room_req.count
    return count


