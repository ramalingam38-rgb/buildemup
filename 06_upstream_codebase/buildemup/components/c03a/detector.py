def _detect_ec001(
    gap_analysis: DesignGapAnalysis, brief: Brief
) -> Optional[ExtremeCase]:
    """EC-001: TOTAL_AREA_EXCEEDS_ENVELOPE (SPATIAL)

    Detection: sum(room_minimums) × 1.30 > envelope × floors
    Uses NBC-compliant setbacks envelope.
    """
    min_buildable_per_floor = _compute_min_buildable_per_floor_sqm(brief)
    nbc_envelope_per_floor = _compute_envelope_area_sqm(
        brief, use_nbc_setbacks=True
    )

    if min_buildable_per_floor <= nbc_envelope_per_floor:
        return None

    # Convert to sqft for user message
    available_sqft = nbc_envelope_per_floor * SQM_TO_SQFT
    required_sqft = min_buildable_per_floor * SQM_TO_SQFT
    floors = len(brief.floors)
    total_buildable_sqft = available_sqft * floors
    total_required_sqft = required_sqft * floors
    shortfall_sqft = total_required_sqft - total_buildable_sqft

    # Trace back to C2's envelope_sufficiency CheckResult if HARD_FAIL'd
    related_check = _find_check_in_blocking(
        gap_analysis.practical_report, "envelope_sufficiency"
    )
    blocking_gap_ids = (("envelope_sufficiency",) if related_check else ())

    user_facing_message = (
        f"Your plot fits about {available_sqft:.0f} sqft per floor "
        f"across {floors} floors = {total_buildable_sqft:.0f} sqft total. "
        f"The rooms in your brief need at least {total_required_sqft:.0f} "
        f"sqft. You're short by about {shortfall_sqft:.0f} sqft."
    )

    framing_line = (
        "Your plot doesn't have enough buildable area for everything in "
        "your brief. One of these trade-offs is necessary to make it work."
    )

    return ExtremeCase(
        case_id=ExtremeCaseId.EC_001_TOTAL_AREA_EXCEEDS_ENVELOPE,
        category=ExtremeCaseCategory.SPATIAL,
        blocking_gap_ids=blocking_gap_ids,
        user_facing_message=user_facing_message,
        framing_line=framing_line,
        resolution_probability=ResolutionProbability.NOT_APPLICABLE,
        options=_make_placeholder_options(),
        detected_at_iteration=0,
    )


def _detect_ec002(
    gap_analysis: DesignGapAnalysis, brief: Brief
) -> Optional[ExtremeCase]:
    """EC-002: PLOT_WIDTH_INSUFFICIENT (SITE)

    Three-tier detection:
      Physical (< 12/14/16 ft): HARD_FAIL handled upstream → return None
      Severe (14-15 ft 2BHK / 16-18 ft 3BHK): EC-002 fires
      Comfortable (>= 5.5m 2BHK / 6.7m 3BHK): no EC → return None
    """
    plot_width_m = brief.plot.width_m
    plot_width_ft = plot_width_m * M_TO_FT
    bhk = _bhk_count(brief)

    if bhk == 0:
        return None  # No bedrooms — width tiers don't apply

    # Determine tier thresholds based on BHK
    if bhk <= 2:
        physical_threshold_ft = EC_002_PHYSICAL_TIER_FT["2bhk"]
        comfortable_threshold_m = EC_002_COMFORTABLE_TIER_M["2bhk"]
    else:  # 3+ BHK
        physical_threshold_ft = EC_002_PHYSICAL_TIER_FT["3bhk"]
        comfortable_threshold_m = EC_002_COMFORTABLE_TIER_M["3bhk"]

    # Tier 1 — Physical: HARD_FAIL handled upstream
    if plot_width_ft < physical_threshold_ft:
        return None

    # Tier 3 — Comfortable: no EC
    if plot_width_m >= comfortable_threshold_m:
        return None

    # Tier 2 — Severe range: detector fires
    estimated_bedroom_width_ft = plot_width_ft - 4  # accounts for typical setbacks + walls

    user_facing_message = (
        f"Your plot is {plot_width_ft:.1f} ft wide. A {bhk}BHK home is "
        f"buildable here, but bedrooms will be narrow "
        f"(about {estimated_bedroom_width_ft:.1f} ft) and furniture "
        f"choices will be constrained (no king beds, wardrobes shallower "
        f"than standard, single-loaded corridor only)."
    )

    framing_line = (
        "Plots this width work, but the layout has real compromises. "
        "We want you to know what you're choosing."
    )

    return ExtremeCase(
        case_id=ExtremeCaseId.EC_002_PLOT_WIDTH_INSUFFICIENT,
        category=ExtremeCaseCategory.SITE,
        blocking_gap_ids=(),  # Purely computed; no C2 check
        user_facing_message=user_facing_message,
        framing_line=framing_line,
        resolution_probability=ResolutionProbability.NOT_APPLICABLE,
        options=_make_placeholder_options(),
        detected_at_iteration=0,
    )


