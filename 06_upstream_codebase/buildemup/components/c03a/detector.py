CIRCULATION_FACTOR = 1.35  # B-004 (S54 fix)

# B-004 (S54 May 2026): aligned with C2's hard_physics_checks.py and
# C1's room_minimums.json "typical" value (also 1.35). Prior 1.30 came
# from an outdated SPEC EC-001 reference and produced inconsistent
# detection thresholds vs C2's envelope check. Single source of truth
# is now IS 3861-2002-derived "typical residential" 1.35 across
# C1 / C2 / C3a. (Note: kb_rules/room_minimums.json also exposes
# 1.40 for small homes and 1.30 for large — full per-size sourcing
# is a future v1.x backlog item.)

# EC-002 plot width tiers
EC_002_PHYSICAL_TIER_FT = {  # < this width → HARD_FAIL handled upstream
    "any": 12,
    "2bhk": 14,
    "3bhk": 16,
}
EC_002_SEVERE_TIER_RANGES_FT = {  # detector fires EC-002 in these ranges
    "2bhk": (14, 15),
    "3bhk": (16, 18),
}
EC_002_COMFORTABLE_TIER_M = {  # >= this width → no EC, soft note in layout
    "2bhk": 5.5,  # Neufert
    "3bhk": 6.7,
}

# EC-010 vs EC-004/005/007 dedup
EC_004_005_007_CHECK_IDS = frozenset({
    "far_compliance",
    "ground_coverage_compliance",
    "stilt_mandate_compliance",
})

EC_010_CHECK_IDS = frozenset({
    "fire_tender_access",
    "electric_line_clearance",
    "water_course_clearance",
})

EC_010_FIXED_PROBABILITY = {
    "fire_tender_access": ResolutionProbability.MEDIUM,
    "water_course_clearance": ResolutionProbability.LOW,
}

# EC budget ratios
EC_008_HARD_RATIO = 1.5
EC_009_BUDGET_BUFFER_RATIO = 1.2

# Unit conversions
SQM_TO_SQFT = 10.7639
M_TO_FT = 3.28084


