def _make_placeholder_options() -> tuple[ResolutionOption, ...]:
    """Two placeholder options to satisfy ExtremeCase.__post_init__'s
    >=2 options invariant. S3's option_generator.py replaces these
    with real ResolutionOption instances tailored per EC.

    DO NOT TEST OPTION CONTENT IN S2 — only test case detection.
    """
    placeholder = ResolutionOption(
        option_id="PLACEHOLDER_S3_FILLS_IN",
        description="(option set will be generated by S3)",
        impact_summary="(impact will be computed by S3)",
        cost_impact=None,
        space_impact_sqft=0,
        recommended=False,
        recommendation_reason=None,
        requires_brief_change=(),
        requires_action=None,
        risk_advisory=None,
        is_preview_mode=False,
    )
    # ExtremeCase.__post_init__ doesn't enforce option_id uniqueness,
    # so two identical placeholders are fine. ExtremeDecision later
    # will need distinct option_ids — S3's responsibility.
    return (placeholder, placeholder)


